function getTranslation(key) {
    const lang = localStorage.getItem('nubeware_lang') || 'es';
    return translations[lang][key] || key;
}

function changeLanguage(lang) {
    localStorage.setItem('nubeware_lang', lang);
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[lang] && translations[lang][key]) {
            if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
                el.placeholder = translations[lang][key];
            } else {
                el.textContent = translations[lang][key];
            }
        }
    });
    
    // Update active state of buttons
    document.querySelectorAll('.lang-btn-select').forEach(btn => {
        if (btn.getAttribute('data-lang') === lang) {
            btn.classList.add('active');
        } else {
            btn.classList.remove('active');
        }
    });

    // Update active state for mobile buttons
    document.querySelectorAll('.mobile-lang-btn').forEach(btn => {
        if (btn.getAttribute('data-lang') === lang) {
            btn.style.background = 'rgba(14,165,233,0.1)';
            btn.style.borderColor = 'var(--color-primary)';
            btn.style.color = 'var(--color-primary)';
        } else {
            btn.style.background = 'white';
            btn.style.borderColor = 'var(--color-slate-200)';
            btn.style.color = 'var(--color-slate-600)';
        }
    });
}

// Initialize on load
document.addEventListener('DOMContentLoaded', () => {
    const savedLang = localStorage.getItem('nubeware_lang') || 'es';
    changeLanguage(savedLang);
});
